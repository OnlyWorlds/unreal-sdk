#!/usr/bin/env python3
"""The shared layout fixture's anchors -> Plugin/OnlyWorlds/Core/Private/OWLayoutAnchors.generated.cpp (the table
OWLayout::LayoutByKind reads).

    python codegen/generate_layout.py            # write the table
    python codegen/generate_layout.py --check    # exit 1 if the table would change (the drift guard)

Standard library only. LayoutByKind starts each kind of element at a point on a circle and pulls it back there. The
method is chaotic: one anchor one unit in the last place off moves a large world's picture by a tenth of its frame.
Cosine and sine are not correctly rounded and differ between runtimes, so the anchors are never computed at run time:
they are one table of 253 points (for k kinds, k = 1 to 22, the k points, flat, the points of k from index k * (k - 1)),
the same float64 values the npm SDK and the Python package hold, read here from the vendored copy of the shared fixture
(tests/data/by-kind.json, its `anchors`; Python's json reads a decimal exactly) and written as bit patterns, so no
parser of a decimal literal stands between the fixture and the table.

  tests/data/by-kind.json                                        the npm SDK's test/fixtures/layout/by-kind.json, byte for byte
  -> Plugin/OnlyWorlds/Core/Private/OWLayoutAnchors.generated.cpp  OWLayout::AnchorBits

Written LF-only, as the repo's .gitattributes keeps it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "tests" / "data" / "by-kind.json"
OUT = ROOT / "Plugin" / "OnlyWorlds" / "Core" / "Private" / "OWLayoutAnchors.generated.cpp"
KINDS = 22


def flat_anchors(table: dict) -> list[float]:
    if sorted(table, key=int) != [str(k) for k in range(1, KINDS + 1)]:
        raise ValueError(f"the anchor table holds k = 1 to {KINDS}, each once")
    flat: list[float] = []
    for k in range(1, KINDS + 1):
        row = table[str(k)]
        if not isinstance(row, list) or len(row) != k:
            raise ValueError(f"k = {k} does not hold {k} points")
        for p in row:
            if not isinstance(p, list) or len(p) != 2 or not all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in p):
                raise ValueError(f"k = {k} holds a point that is not [x, y]")
            flat += [float(p[0]), float(p[1])]
    return flat


def render() -> str:
    data = FIXTURE.read_bytes()
    flat = flat_anchors(json.loads(data.decode("utf-8"))["anchors"])
    lines = [
        f"// GENERATED by codegen/generate_layout.py from tests/data/by-kind.json (sha256 {hashlib.sha256(data).hexdigest()}),",
        "// its anchors. Do not edit: regenerate.",
        "",
        '#include "OWLayout.h"',
        "",
        "namespace OnlyWorlds {",
        "namespace OWLayout {",
        "",
        "// For each count of kinds k from 1 to 22, the k points (x, y) on the unit circle, flat, k = 1 first; the points of k",
        "// start at index k * (k - 1). Bit patterns of the shared fixture's float64 numbers.",
        f"const uint64_t AnchorBits[AnchorCount] = {{",
    ]
    for i in range(0, len(flat), 2):
        x, y = flat[i], flat[i + 1]
        bx = struct.pack(">d", x).hex().upper()
        by = struct.pack(">d", y).hex().upper()
        lines.append(f"    0x{bx}ull, 0x{by}ull,  // {x!r}, {y!r}")
    lines += [
        "};",
        f"static_assert(sizeof(AnchorBits) / sizeof(AnchorBits[0]) == {len(flat)}, \"253 points\");",
        "",
        "}  // namespace OWLayout",
        "}  // namespace OnlyWorlds",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the table would change")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_bytes().decode("utf-8") != text:
            print(f"stale: {OUT.relative_to(ROOT)} (run python codegen/generate_layout.py)", file=sys.stderr)
            return 1
        print(f"ok: {OUT.relative_to(ROOT)} matches tests/data/by-kind.json")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
