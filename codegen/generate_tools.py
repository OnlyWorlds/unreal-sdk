#!/usr/bin/env python3
"""The OnlyWorlds tools list -> Core/Private/OWTools.generated.cpp (OWTools::All()), the rows OWOpeners reads.

    python codegen/generate_tools.py                 check the vendored file against the pin, write the C++
    python codegen/generate_tools.py --check         exit 1 if the vendored file or the C++ is stale
    python codegen/generate_tools.py --repin COMMIT  vendor tools.json as GitHub serves it at COMMIT, pin it, write

Standard library only. The list (github.com/OnlyWorlds/tools, tools.json) is vendored byte for byte at
codegen/tools/tools.json and pinned in codegen/tools-pin.json (the commit and the file's sha256), apart from the
schema-dist pin (codegen/PIN) because it moves on its own; the npm SDK and the Python package pin the same commit. A
tool listed after a release is offered from the next one. Only the keys OpenersFor reads are baked (id, name, url,
client, rung, open); the rest of each row (the checks, the maker) stays in the list. OWOpeners.h declares the table.
Written LF-only; build.cmd and UBT both compile it with the rest of Core/Private.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path
from typing import Any

CODEGEN = Path(__file__).resolve().parent
ROOT = CODEGEN.parent
VENDORED = CODEGEN / "tools" / "tools.json"
PIN = CODEGEN / "tools-pin.json"
OUT = ROOT / "Plugin" / "OnlyWorlds" / "Core" / "Private" / "OWTools.generated.cpp"
REPO = "https://github.com/OnlyWorlds/tools"
KEYS = ("id", "name", "url", "client", "rung", "open")


def die(msg: str) -> None:
    raise SystemExit(f"tools: {msg}")


def text(value: Any, where: str, optional: bool) -> str:
    """A JSON string as a C++ literal (JSON's escapes are C++'s for these characters; /utf-8 keeps \\u as UTF-8)."""
    if value is None and optional:
        return "std::nullopt"
    if isinstance(value, str):
        return json.dumps(value)
    die(f"{where} is {value!r}; this generator bakes a string{' or null' if optional else ''}")
    return ""


def row(t: dict[str, Any]) -> str:
    rid = t.get("id")
    missing = [k for k in KEYS if k not in t]
    if missing:
        die(f"row {rid!r} has no {', '.join(missing)}")
    head = ", ".join(text(t[k], f"row {rid!r} {k}", k == "client") for k in KEYS[:5])
    o = t["open"]
    if o is None:
        door = "std::nullopt"
    elif isinstance(o, dict):
        parts = [text(o.get(k), f"row {rid!r} open.{k}", True) for k in ("world", "element", "needs")]
        skips = o.get("element_skips")
        if skips is not None:
            # A list of words (open.element_skips), in the list's own order; absent or null bakes none.
            if not (isinstance(skips, list) and all(isinstance(v, str) for v in skips)):
                die(f"row {rid!r} open.element_skips is {skips!r}; this generator bakes a list of words or null")
            parts.append("{" + ", ".join(json.dumps(v) for v in skips) + "}")
        types = o.get("element_types")
        if types is not None:
            # The type words the element door opens (open.element_types), in the list's own order; absent or null
            # bakes none (every type), so a row without the key bakes as before.
            if not (isinstance(types, list) and all(isinstance(v, str) for v in types)):
                die(f"row {rid!r} open.element_types is {types!r}; this generator bakes a list of words or null")
            if skips is None:
                parts.append("{}")
            parts.append("std::vector<std::string>{" + ", ".join(json.dumps(v) for v in types) + "}")
        if "opens_public" in o:
            # open.opens_public, baked only when the row carries it, so a row without the key bakes as before; the
            # aggregate's earlier members are filled in first.
            if not isinstance(o["opens_public"], bool):
                die(f"row {rid!r} open.opens_public is {o['opens_public']!r}; true or false")
            if skips is None and types is None:
                parts.append("{}")
            if types is None:
                parts.append("std::nullopt")
            parts.append("true" if o["opens_public"] else "false")
        door = "OWToolOpen{" + ", ".join(parts) + "}"
    else:
        die(f"row {rid!r} open is {o!r}; an object or null")
    return f"        {{{head},\n         {door}}},\n"


def render(data: bytes, pin: dict[str, Any]) -> str:
    doc = json.loads(data.decode("utf-8"))
    if doc.get("format") != 1:
        die(f"tools.json format {doc.get('format')!r}; this generator reads format 1")
    if not isinstance(doc.get("tools"), list):
        die("tools.json has no tools array")
    rows = "".join(row(t) for t in doc["tools"])
    return (
        f"// GENERATED by codegen/generate_tools.py from the OnlyWorlds tools list, {REPO} @ {pin['commit']}\n"
        f"// (tools.json sha256 {pin['sha256']}).\n"
        "// Do not edit: the list is changed upstream, repinned (python codegen/generate_tools.py --repin <commit>) and\n"
        "// regenerated.\n"
        "\n"
        '#include "OWOpeners.h"\n'
        "\n"
        "namespace OnlyWorlds {\n"
        "namespace OWTools {\n"
        "\n"
        f'const char* const Repository = "{REPO}";\n'
        f'const char* const Commit = "{pin["commit"]}";\n'
        f'const char* const Sha256 = "{pin["sha256"]}";\n'
        "\n"
        "const std::vector<OWTool>& All() {\n"
        "    static const std::vector<OWTool> rows = {\n"
        f"{rows}"
        "    };\n"
        "    return rows;\n"
        "}\n"
        "\n"
        "}  // namespace OWTools\n"
        "}  // namespace OnlyWorlds\n"
    )


def read_pinned() -> tuple[dict[str, Any], bytes]:
    pin: dict[str, Any] = json.loads(PIN.read_text(encoding="utf-8"))
    data = VENDORED.read_bytes()
    got = hashlib.sha256(data).hexdigest()
    if got != pin["sha256"]:
        die(f"codegen/tools/tools.json is sha256 {got}; the pin says {pin['sha256']}")
    return pin, data


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if the vendored file or the C++ is stale")
    mode.add_argument("--repin", metavar="COMMIT", help="vendor tools.json at COMMIT (40 hex), pin it, write")
    args = ap.parse_args()
    if args.repin is not None:
        if not re.fullmatch(r"[0-9a-f]{40}", args.repin):
            die("--repin takes the full 40-hex commit")
        url = f"https://raw.githubusercontent.com/OnlyWorlds/tools/{args.repin}/tools.json"
        with urllib.request.urlopen(url, timeout=30) as res:
            data = res.read()
        pin = {
            "_what": "The recorded pin for the vendored OnlyWorlds tools list (codegen/tools/tools.json, byte for byte"
            " as GitHub serves it at the commit). Do not edit by hand: python codegen/generate_tools.py --repin"
            " <commit>, and review the diff. Kept equal to the npm SDK's and the Python package's pins on purpose.",
            "repo": REPO,
            "commit": args.repin,
            "sha256": hashlib.sha256(data).hexdigest(),
            "pinned_at": datetime.date.today().isoformat(),
        }
        VENDORED.parent.mkdir(exist_ok=True)
        VENDORED.write_bytes(data)
        PIN.write_bytes((json.dumps(pin, indent=2) + "\n").encode("utf-8"))
        OUT.write_bytes(render(data, pin).encode("utf-8"))
        print(f"pinned {args.repin}, sha256 {pin['sha256']}; wrote {OUT.name}")
        return 0
    pin, data = read_pinned()
    want = render(data, pin).encode("utf-8")
    if args.check:
        if not OUT.is_file() or OUT.read_bytes() != want:
            print(f"DRIFT: {OUT.relative_to(ROOT).as_posix()} is not what the pinned tools list generates", file=sys.stderr)
            return 1
        print(f"no drift: {OUT.name} matches the tools list at {pin['commit']}")
        return 0
    OUT.write_bytes(want)
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} from the tools list at {pin['commit']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
