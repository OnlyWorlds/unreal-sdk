#!/usr/bin/env python3
"""The by-links-3d directions table -> Plugin/OnlyWorlds/Core/Private/OWLayoutDirections.generated.cpp (the table
OWLayout::LayoutByLinks3d reads).

    python codegen/generate_layout_3d.py            # write the table
    python codegen/generate_layout_3d.py --check    # exit 1 if the table would change (the drift guard)

Standard library only. by-links-3d sends each part of a run's body off in a direction read from a table, never computed
(the default layouts page, its directions table paragraph): for each count of parts K from 1 to 37, K unit vectors
[x, y, z]. This reads the pinned dist's own copy (codegen/schema-dist/profiles/layout-by-links-3d.directions.json, whose
sha256 the method's fixture names as table_sha256; Python's json reads a decimal exactly, and `-0.0` as -0) and writes
the doubles as bit patterns, so no parser of a decimal literal stands between the table and the method, and a zero
written -0.0 stays -0. The shape of generate_layout.py's anchor table, flat: the vectors of K from index
3 * K * (K - 1) / 2, three doubles each.

  codegen/schema-dist/profiles/layout-by-links-3d.directions.json   the pinned dist's directions table, vendored
  -> Plugin/OnlyWorlds/Core/Private/OWLayoutDirections.generated.cpp  OWLayout::DirectionBits

Written LF-only, as the repo's .gitattributes keeps it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "codegen" / "schema-dist" / "profiles" / "layout-by-links-3d.directions.json"
OUT = ROOT / "Plugin" / "OnlyWorlds" / "Core" / "Private" / "OWLayoutDirections.generated.cpp"
K_MAX = 37


def flat_directions(doc: dict) -> list[float]:
    if doc.get("k_max") != K_MAX:
        raise ValueError(f"the table's k_max is {doc.get('k_max')!r}, not {K_MAX}")
    table = doc["directions"]
    if sorted(table, key=int) != [str(k) for k in range(1, K_MAX + 1)]:
        raise ValueError(f"the directions table holds K = 1 to {K_MAX}, each once")
    flat: list[float] = []
    for k in range(1, K_MAX + 1):
        row = table[str(k)]
        if not isinstance(row, list) or len(row) != k:
            raise ValueError(f"K = {k} does not hold {k} vectors")
        for v in row:
            if not isinstance(v, list) or len(v) != 3 or not all(isinstance(c, float) for c in v):
                raise ValueError(f"K = {k} holds a vector that is not three doubles [x, y, z]")
            flat += v
    return flat


def render() -> str:
    data = TABLE.read_bytes()
    flat = flat_directions(json.loads(data.decode("utf-8")))
    lines = [
        "// GENERATED by codegen/generate_layout_3d.py from codegen/schema-dist/profiles/layout-by-links-3d.directions.json",
        f"// (sha256 {hashlib.sha256(data).hexdigest()}). Do not edit: regenerate.",
        "",
        '#include "OWLayout.h"',
        "",
        "namespace OnlyWorlds {",
        "namespace OWLayout {",
        "",
        f"// For each count of parts K from 1 to {K_MAX}, the K unit vectors (x, y, z), flat, K = 1 first; the vectors of K",
        "// start at index 3 * K * (K - 1) / 2. Bit patterns of the shared table's float64 numbers (a -0.0 kept).",
        "const uint64_t DirectionBits[DirectionCount] = {",
    ]
    for i in range(0, len(flat), 3):
        v = flat[i:i + 3]
        bits = ", ".join(f"0x{struct.pack('>d', c).hex().upper()}ull" for c in v)
        lines.append(f"    {bits},  // {', '.join(repr(c) for c in v)}")
    lines += [
        "};",
        f"static_assert(sizeof(DirectionBits) / sizeof(DirectionBits[0]) == {len(flat)}, \"{len(flat) // 3} vectors\");",
        "",
        "}  // namespace OWLayout",
        "}  // namespace OnlyWorlds",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the table would change")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_bytes().decode("utf-8") != text:
            print(f"stale: {OUT.relative_to(ROOT)} (run python codegen/generate_layout_3d.py)", file=sys.stderr)
            return 1
        print(f"ok: {OUT.relative_to(ROOT)} matches codegen/schema-dist/profiles/layout-by-links-3d.directions.json")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
