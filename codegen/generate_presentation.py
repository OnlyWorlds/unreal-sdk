#!/usr/bin/env python3
"""The core's presentation sidecar: each type's colour word and icon, from schema-dist's presentation.json.

    python codegen/generate_presentation.py            # verify the vendored dist against the pin, then write the output
    python codegen/generate_presentation.py --check    # verify, then exit 1 if the output would change (the drift guard)

Standard library only. It shares generate.py's pin check (the vendored tree is what codegen/PIN says, or nothing is
written). What it reads and writes:

  codegen/schema-dist/presentation.json   colors.order (the colour words, in order) and, per type, its family (one of
                                          those words), its icon and its public fields
  codegen/schema-dist/schema.json         the 22 types, so the sidecar has one row for each and no other
  -> Plugin/OnlyWorlds/Core/Private/OWPresentation.generated.cpp   OWPresentation.h's functions over the table

A family word not in colors.order fails loudly, naming the word, and nothing is written (the lens profile's nodes,
presentation.json `_meta.groups`): a reader never draws a default colour. The generated table carries a static_assert
of the same rule, so a hand edit that breaks it does not build. Colour values are the tool's and are not read.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from generate import DIST, ROOT, read_pin, verify_dist

PRESENTATION = DIST / "presentation.json"
SCHEMA = DIST / "schema.json"
OUT = ROOT / "Plugin" / "OnlyWorlds" / "Core" / "Private" / "OWPresentation.generated.cpp"


def refusal(presentation: dict, slugs: list[str]) -> str:
    """Why the sidecar cannot be read: the first type in the standard's order with no entry, or whose family is not
    one of colors.order, named with its word; a type the standard does not have; "" when it reads."""
    order = presentation["colors"]["order"]
    types = presentation["types"]
    for slug in slugs:
        t = types.get(slug)
        if not isinstance(t, dict):
            return f"presentation.json: {slug} has no entry"
        if t.get("family") not in order:
            return f"presentation.json: {slug}'s family {json.dumps(t.get('family'))} is not one of {', '.join(order)}"
        if not isinstance(t.get("icon"), str) or not t["icon"]:
            return f"presentation.json: {slug} has no icon"
    for slug in types:
        if slug not in slugs:
            return f"presentation.json: {slug} is not one of the 22 types"
    return ""


def c(text: str) -> str:
    """A C++ string literal; the sidecar's words are ASCII, and anything else is refused rather than escaped."""
    if not text.isascii() or '"' in text or "\\" in text:
        sys.exit(f"presentation.json: {text!r} is not a plain ASCII word")
    return f'"{text}"'


def emit(presentation: dict, slugs: list[str], tag: str) -> str:
    order = presentation["colors"]["order"]
    types = presentation["types"]
    out = [
        f"// GENERATED by codegen/generate_presentation.py from schema-dist {tag} (presentation.json). Do not edit:",
        "// regenerate.",
        "",
        '#include "OWPresentation.h"',
        "",
        "#include <iterator>",
        "#include <string_view>",
        "#include <utility>",
        "",
        "namespace OnlyWorlds {",
        "namespace OWPresentation {",
        "",
        "namespace {",
        "",
        "struct Row {",
        "    const char* type;",
        "    const char* family;",
        "    const char* icon;",
        "};",
        "",
        "// colors.order.",
        "constexpr const char* Words[] = {" + ", ".join(c(w) for w in order) + "};",
        "",
        "// types, in the sidecar's order (schema.json's).",
        "constexpr Row Rows[] = {",
    ]
    out += [f"    {{{c(s)}, {c(types[s]['family'])}, {c(types[s]['icon'])}}}," for s in slugs]
    out += [
        "};",
        "",
        "constexpr bool IsWord(std::string_view w) {",
        "    for (const char* word : Words)",
        "        if (w == word) return true;",
        "    return false;",
        "}",
        "",
        "constexpr bool EveryFamilyIsAWord() {",
        "    for (const Row& r : Rows)",
        "        if (!IsWord(r.family)) return false;",
        "    return true;",
        "}",
        "",
        "// A family word not in colors.order fails loudly: the generator names it, and a hand edit does not build.",
        'static_assert(EveryFamilyIsAWord(), "presentation: a family word is not one of colors.order");',
        "",
        "const Row* RowOf(std::string_view type) {",
        "    for (const Row& r : Rows)",
        "        if (type == r.type) return &r;",
        "    return nullptr;",
        "}",
        "",
        "}  // namespace",
        "",
        "const std::vector<std::string>& Order() {",
        "    static const std::vector<std::string> words(std::begin(Words), std::end(Words));",
        "    return words;",
        "}",
        "",
        "const std::vector<std::string>& Types() {",
        "    static const std::vector<std::string> slugs = [] {",
        "        std::vector<std::string> out;",
        "        for (const Row& r : Rows) out.push_back(r.type);",
        "        return out;",
        "    }();",
        "    return slugs;",
        "}",
        "",
        "std::string FamilyOf(std::string_view type) {",
        "    const Row* r = RowOf(type);",
        "    return r ? r->family : std::string();",
        "}",
        "",
        "std::string IconOf(std::string_view type) {",
        "    const Row* r = RowOf(type);",
        "    return r ? r->icon : std::string();",
        "}",
        "",
        "const std::vector<std::string>& PublicOf(std::string_view type) {",
        "    static const std::vector<std::string> none;",
        "    static const std::vector<std::pair<std::string, std::vector<std::string>>> table = {",
    ]
    for s in slugs:
        fields = types[s].get("public") or []
        out.append(f"        {{{c(s)}, {{{', '.join(c(f) for f in fields)}}}}},")
    out += [
        "    };",
        "    for (const auto& [t, fields] : table)",
        "        if (t == type) return fields;",
        "    return none;",
        "}",
        "",
        "}  // namespace OWPresentation",
        "}  // namespace OnlyWorlds",
        "",
    ]
    return "\n".join(out)


def outputs() -> dict[Path, str]:
    pin = read_pin()
    problems = verify_dist(pin)
    if problems:
        for p in problems:
            print("FAIL:", p)
        sys.exit("The vendored dist is not what the pin says. Re-vendor from the pinned tag; never edit a hash.")
    presentation = json.loads(PRESENTATION.read_text(encoding="utf-8"))
    slugs = list(json.loads(SCHEMA.read_text(encoding="utf-8"))["types"])
    bad = refusal(presentation, slugs)
    if bad:
        sys.exit(bad)
    return {OUT: emit(presentation, slugs, pin["tag"])}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the output would change")
    a = ap.parse_args()
    pin = read_pin()
    drift = 0
    files = outputs()
    print(f"dist OK: {pin['tag']}, MANIFEST.json sha256 {pin['manifest_sha256'][:12]}... matches the pin")
    for path, text in files.items():
        data = text.encode("utf-8")
        if a.check:
            if not path.is_file() or path.read_bytes() != data:
                print("DRIFT:", path.relative_to(ROOT).as_posix())
                drift += 1
        elif not path.is_file() or path.read_bytes() != data:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print("wrote", path.relative_to(ROOT).as_posix())
    if a.check:
        print("no drift" if not drift else f"{drift} file(s) drifted: run codegen/generate_presentation.py")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
