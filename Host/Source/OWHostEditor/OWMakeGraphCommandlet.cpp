DEFINE_LOG_CATEGORY_STATIC(LogOWMakeGraph, Log, All);

namespace
{
	// The graphs' folder: the host's Content/OW/, generated by this commandlet and left out of git (.gitignore), cooked
	// by DefaultGame.ini's DirectoriesToAlwaysCook although no map references it.
	const TCHAR* const OWGraphFolder = TEXT("/Game/OW/");

	FEdGraphPinType OWPinType(const FName Category, UObject* SubObject = nullptr)
	{
		FEdGraphPinType Made;
		Made.PinCategory = Category;
		Made.PinSubCategoryObject = SubObject;
		return Made;
	}

	// A call node placed as the editor places one (EdGraph.h's FGraphNodeCreator: a GUID, PostPlacedNewNode,
	// AllocateDefaultPins), as the graph tests' PlaceCall does; nullptr when the class has no such function.
	UK2Node_CallFunction* PlaceOWCall(UEdGraph& Graph, UClass* Owner, const TCHAR* FunctionName)
	{
		const UFunction* Function = Owner->FindFunctionByName(FunctionName);
		if (!Function) return nullptr;
		FGraphNodeCreator<UK2Node_CallFunction> Creator(Graph);
		UK2Node_CallFunction* Node = Creator.CreateNode(false);
		Node->SetFromFunction(Function);
		Creator.Finalize();
		return Node;
	}

	// One Blueprint of UObject in its own package, its one function ReadWorld(Path, Id) -> ElementCount, ElementName,
	// Error: OpenWorldFolder(Path) on the exec line, then the opened world's GetElementCount and GetElementName(Id)
	// read into the result, the folder's Error beside them. bWrongName wires the world's GetWorldName into ElementName
	// instead. Compiled by the Kismet compiler, then saved. False, with the reason logged as an error, when a link is
	// refused, the compile has an error, or the save fails.
	bool MakeGraph(const FString& AssetName, const bool bWrongName)
	{
		const FString PackageName = FString(OWGraphFolder) + AssetName;
		UPackage* Package = CreatePackage(*PackageName);
		if (!Package || FindObject<UBlueprint>(Package, *AssetName))
		{
			UE_LOG(LogOWMakeGraph, Error, TEXT("OWMakeGraph: %s is already loaded in this process; nothing written"), *PackageName);
			return false;
		}
		UBlueprint* BP = FKismetEditorUtilities::CreateBlueprint(UObject::StaticClass(), Package, FName(*AssetName), BPTYPE_Normal,
			UBlueprint::StaticClass(), UBlueprintGeneratedClass::StaticClass(), NAME_None);
		UEdGraph* Graph = FBlueprintEditorUtils::CreateNewGraph(BP, TEXT("ReadWorld"), UEdGraph::StaticClass(), UEdGraphSchema_K2::StaticClass());
		FBlueprintEditorUtils::AddFunctionGraph<UClass>(BP, Graph, /*bIsUserCreated=*/true, nullptr);
		TArray<UK2Node_FunctionEntry*> Entries;
		Graph->GetNodesOfClass(Entries);
		UK2Node_FunctionEntry* Entry = Entries.Num() == 1 ? Entries[0] : nullptr;
		if (!Entry)
		{
			UE_LOG(LogOWMakeGraph, Error, TEXT("OWMakeGraph: %s: the function graph has %d entry nodes, not one"), *PackageName, Entries.Num());
			return false;
		}
		UK2Node_FunctionResult* Result = FBlueprintEditorUtils::FindOrCreateFunctionResultNode(Entry);

		const FName StringPin = UEdGraphSchema_K2::PC_String;
		UEdGraphPin* InPath = Entry->CreateUserDefinedPin(TEXT("Path"), OWPinType(StringPin), EGPD_Output);
		UEdGraphPin* InId = Entry->CreateUserDefinedPin(TEXT("Id"), OWPinType(StringPin), EGPD_Output);
		UEdGraphPin* OutCount = Result->CreateUserDefinedPin(TEXT("ElementCount"), OWPinType(UEdGraphSchema_K2::PC_Int), EGPD_Input);
		UEdGraphPin* OutName = Result->CreateUserDefinedPin(TEXT("ElementName"), OWPinType(StringPin), EGPD_Input);
		UEdGraphPin* OutError = Result->CreateUserDefinedPin(TEXT("Error"), OWPinType(StringPin), EGPD_Input);

		UK2Node_CallFunction* OpenNode = PlaceOWCall(*Graph, UOWLibrary::StaticClass(), TEXT("OpenWorldFolder"));
		UK2Node_CallFunction* CountNode = PlaceOWCall(*Graph, UOWWorld::StaticClass(), TEXT("GetElementCount"));
		UK2Node_CallFunction* NameNode = PlaceOWCall(*Graph, UOWWorld::StaticClass(), bWrongName ? TEXT("GetWorldName") : TEXT("GetElementName"));
		if (!OpenNode || !CountNode || !NameNode)
		{
			UE_LOG(LogOWMakeGraph, Error, TEXT("OWMakeGraph: %s: the plugin has no OpenWorldFolder, GetElementCount or %s"), *PackageName,
				bWrongName ? TEXT("GetWorldName") : TEXT("GetElementName"));
			return false;
		}

		// Every link through the K2 schema, as a person drags one; a refused one is counted, never forced.
		const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
		int32 Links = 0, Refused = 0;
		auto Join = [Schema, &Links, &Refused](UEdGraphPin* From, UEdGraphPin* To)
		{
			++Links;
			if (!From || !To || !Schema->TryCreateConnection(From, To)) ++Refused;
		};
		const FName ReturnPin = UEdGraphSchema_K2::PN_ReturnValue, SelfPin = UEdGraphSchema_K2::PN_Self;
		Join(Entry->GetThenPin(), OpenNode->GetExecPin());
		Join(OpenNode->GetThenPin(), Result->GetExecPin());
		Join(InPath, OpenNode->FindPin(TEXT("Path")));
		Join(OpenNode->FindPin(TEXT("Error")), OutError);
		UEdGraphPin* Opened = OpenNode->FindPin(ReturnPin);
		Join(Opened, CountNode->FindPin(SelfPin));
		Join(CountNode->FindPin(ReturnPin), OutCount);
		Join(Opened, NameNode->FindPin(SelfPin));
		if (!bWrongName) Join(InId, NameNode->FindPin(TEXT("Id")));
		Join(NameNode->FindPin(ReturnPin), OutName);

		FCompilerResultsLog Results;
		Results.bSilentMode = true;
		FKismetEditorUtilities::CompileBlueprint(BP, EBlueprintCompileOptions::SkipGarbageCollection, &Results);
		for (const TSharedRef<FTokenizedMessage>& Message : Results.Messages)
		{
			if (Message->GetSeverity() < EMessageSeverity::Info)
				UE_LOG(LogOWMakeGraph, Display, TEXT("OWMakeGraph: %s: compiler: %s"), *PackageName, *Message->ToText().ToString());
		}
		const bool bCompiled = BP->Status == BS_UpToDate && BP->GeneratedClass != nullptr;
		UE_LOG(LogOWMakeGraph, Display, TEXT("OWMakeGraph: %s: ReadWorld, %d nodes, %d links (%d refused), compiled %s with %d errors and %d warnings"),
			*PackageName, Graph->Nodes.Num(), Links, Refused, bCompiled ? TEXT("up to date") : TEXT("NOT up to date"), Results.NumErrors,
			Results.NumWarnings);
		if (Refused > 0 || Results.NumErrors > 0 || !bCompiled)
		{
			UE_LOG(LogOWMakeGraph, Error, TEXT("OWMakeGraph: %s: not saved"), *PackageName);
			return false;
		}

		// Saved as the engine's own commandlets save a package (WorldPartitionCommandletHelpers.cpp, ImportAssetsCommandlet.cpp).
		const FString Filename = FPackageName::LongPackageNameToFilename(PackageName, FPackageName::GetAssetPackageExtension());
		FSavePackageArgs SaveArgs;
		SaveArgs.TopLevelFlags = RF_Public | RF_Standalone;
		SaveArgs.Error = GWarn;
		if (!UPackage::SavePackage(Package, BP, *Filename, SaveArgs))
		{
			UE_LOG(LogOWMakeGraph, Error, TEXT("OWMakeGraph: %s: the save to %s failed"), *PackageName, *Filename);
			return false;
		}
		UE_LOG(LogOWMakeGraph, Display, TEXT("OWMakeGraph: wrote %s (%lld bytes), class %s"), *FPaths::ConvertRelativePathToFull(Filename),
			IFileManager::Get().FileSize(*Filename), *BP->GeneratedClass->GetPathName());
		return true;
	}
}

UOWMakeGraphCommandlet::UOWMakeGraphCommandlet(const FObjectInitializer& ObjectInitializer)
	: Super(ObjectInitializer)
{
	IsClient = false;
	IsServer = false;
	IsEditor = true;
	LogToConsole = true;
	HelpDescription = TEXT("Writes the Blueprint graphs the packaged host runs with -OWGraph into Content/OW/.");
}

int32 UOWMakeGraphCommandlet::Main(const FString& Params)
{
	const bool bMeant = MakeGraph(TEXT("BP_OWBootGraph"), /*bWrongName=*/false);
	const bool bWrong = MakeGraph(TEXT("BP_OWBootGraphWrong"), /*bWrongName=*/true);
	const int32 Code = bMeant && bWrong ? 0 : 1;
	UE_LOG(LogOWMakeGraph, Display, TEXT("OWMakeGraph: done, %d of 2 graphs written, exit %d"), int32(bMeant) + int32(bWrong), Code);
	return Code;
}
